import GameServer from "../../../app";
import IPacketHandler from "../../Interfaces/IPacketHandler";
import C2S_SelectRole from "../C2S/C2S_SelectRole";

class HandleSelectRole implements IPacketHandler<C2S_SelectRole> {
	public get name() {
		return C2S_SelectRole.name;
	}

	public handlePacket(clientId: number, req: C2S_SelectRole): void {
		const connection = GameServer.networkHandler.getConnection(clientId);

		connection.send(
			Buffer.from([
				0x47, 0x26, 0x00, 0x00, 0x00, 0x00, 0x21, 0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x64, 0x65, 0x66,
				0x67, 0x68, 0x69, 0xc8, 0xc9, 0xca, 0xcb, 0xcc, 0xcd, 0xce, 0xcf, 0xd0, 0xd1, 0xd2, 0xd3, 0xd4, 0xd5, 0xd6,
			])
		);
	}
}

export default HandleSelectRole;
